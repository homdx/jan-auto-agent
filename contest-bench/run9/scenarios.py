NEW_COUNTERS = ("presence_empty_transport", "presence_empty_exhausted", "presence_nothink_ignored")


def ck(name, ok, detail=""):
    return {"name": name, "ok": bool(ok), "detail": str(detail)[:300]}


def _counter(r, name):
    v = r.counters.get(name)
    if v is None:
        v = getattr(r.filter, name, None)
    return v


def _same_params(payloads):
    keys = {(p.get("max_tokens"), p.get("temperature")) for p in payloads}
    return len(keys) == 1, sorted(keys, key=str)


def _has_nudge(p):
    return NUDGE in p["messages"][-1]["content"]


def _think_off(p):
    rs = p.get("reasoning")
    return isinstance(rs, dict) and rs.get("exclude") is True


def _classification_lines(r):
    return [m for m in r.log_lines() if "kind=" in m and "empty" in m.lower() and "finish_reason" in m]


_KIND_RE = {k: re.compile(r"empty[\s(=:/\-]*" + k, re.I) for k in ("transport", "exhausted")}


def _says_kind(text, kind):
    return bool(_KIND_RE[kind].search(text or ""))


def _ending_line(r):
    ls = [m for m in r.log_lines(level="WARNING") if "ending unknown" in m]
    return ls[0] if ls else ""


def _unknown_line(r, i=0):
    ls = [m for m in r.log_lines(level="WARNING") if m.startswith(f"Gate1[presence] UNKNOWN 'candidate {i}'")]
    return ls[0] if ls else ""


def _still_unparseable_line(r):
    ls = [m for m in r.log_lines(level="WARNING") if "ending unknown" in m or "still unparseable" in m]
    return ls[0] if ls else ""


