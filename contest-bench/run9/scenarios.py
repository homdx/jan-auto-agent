def _meta_get(meta, field):
    for alias in _META_ALIASES[field]:
        if isinstance(meta, dict) and alias in meta:
            return meta[alias], alias
        if hasattr(meta, alias):
            return getattr(meta, alias), alias
    return "<missing>", None


def _meta_api(L):
    """Find the entrant's metadata API. Returns (kind, callable)."""
    if hasattr(L, "request_completion_ex"):
        return "request_completion_ex", L.request_completion_ex
    for name in dir(L):
        if name.startswith("request_completion") and name != "request_completion":
            return name, getattr(L, name)
    sig = inspect.signature(L.request_completion)
    for pname in ("on_meta", "meta_callback", "on_done", "on_finish", "meta"):
        if pname in sig.parameters:
            return f"request_completion({pname}=)", pname
    return None, None


def _call_meta(L, url, headers, payload, api_format="openai"):
    kind, fn = _meta_api(L)
    if kind is None:
        return None, None, "no meta API found"
    if kind.startswith("request_completion("):
        box = {}
        def cb(m, *a, **k):
            box["m"] = m
        res = L.request_completion(url, headers, payload, 10, stream=True, api_format=api_format, **{fn: cb})
        return kind, (res, box.get("m")), None
    res = fn(url, headers, payload, 10, stream=True, api_format=api_format)
    if isinstance(res, tuple) and len(res) == 2:
        return kind, res, None
    # maybe an object with .text/.meta
    text = getattr(res, "text", None)
    if text is not None:
        return kind, (text, res), None
    return kind, (res, None), "unexpected return shape"


