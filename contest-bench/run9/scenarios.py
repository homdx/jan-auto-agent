    ul = _unknown_line(r)
    reqs = [e for e in r.tracer.events if e["kind"] == "llm_request"]
    resps = [e for e in r.tracer.events if e["kind"] == "llm_response"]
    return [
        ck("L2.UNKNOWN reason counts ladder re-asks only ('after 1 re-ask(s)')", "after 1 re-ask(s)" in ul, ul[:160]),
        ck("L3.trace: one llm_request event per HTTP call (4)", len(reqs) == 4, len(reqs)),
        ck("L3.trace: one llm_response event per HTTP call (4)", len(resps) == 4, len(resps)),
        ck("L3.trace: llm_request params carry the candidate title", all(e["params"].get("candidate") == "candidate 0" for e in reqs), reqs[:1]),
    ]


