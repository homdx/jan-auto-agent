# ───────────────────────────── H. cap log ──────────────────────────────────
def h1_checks(r):
    logs = r.log_lines()
    cap_idx = [i for i, m in enumerate(logs) if "capped at unparseable_max_tokens_cap" in m]
    bad = []
    for i in cap_idx:
        cap_m = re.search(r"capped at unparseable_max_tokens_cap=(\d+)", logs[i])
        cap = int(cap_m.group(1)) if cap_m else None
        nxt = logs[i + 1] if i + 1 < len(logs) else ""
        if "already tried" in nxt:
            mt = re.search(r"max_tokens=(\d+)", nxt)
            if mt and int(mt.group(1)) != cap:
                bad.append((logs[i][-80:], nxt[-90:]))
    r.info["H1.cap_lines"] = len(cap_idx)
